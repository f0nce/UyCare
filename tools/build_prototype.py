from pathlib import Path
import re
r=Path(__file__).resolve().parents[1]/'prototype'
domain=re.sub(r'\bexport ', '', (r/'domain.mjs').read_text())
app=re.sub(r'^import .*?;\n', '', (r/'app.mjs').read_text(), count=1)
(r/'app.js').write_text('// Generated by tools/build_prototype.py from domain.mjs and app.mjs\n(()=>{\n'+domain+'\n'+app+'\n})();\n')
